"""Authentication routes: registration and login.

Two design decisions worth understanding:

1. Registration returns 201 + the created user, NOT a token. Some APIs
   auto-login on register; we don't, because "create account" and
   "prove identity" are separate concerns and conflating them hides bugs
   (e.g. registering with a typo'd email then being unable to recover).

2. Login uses OAuth2PasswordRequestForm (form fields `username`/`password`),
   not JSON. This is the OAuth2 password-grant convention — FastAPI's /docs
   "Authorize" button speaks exactly this format, and every OAuth2 client
   library expects it. Our "username" is the email address.
"""

from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.security import OAuth2PasswordRequestForm
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.security import create_access_token, hash_password, verify_password
from app.database import get_db
from app.models.user import User
from app.schemas.user import UserCreate, UserOut

router = APIRouter(prefix="/auth", tags=["auth"])


@router.post(
    "/register", response_model=UserOut, status_code=status.HTTP_201_CREATED
)
def register(payload: UserCreate, db: Session = Depends(get_db)) -> User:
    # Check-then-insert has a race (two requests at once), but the
    # unique=True DB constraint is the real guard — this check just lets us
    # return a friendly 409 instead of a raw integrity error.
    existing = db.scalar(select(User).where(User.email == payload.email))
    if existing:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Email already registered",
        )
    user = User(email=payload.email, hashed_password=hash_password(payload.password))
    db.add(user)
    db.commit()
    db.refresh(user)  # populate id/created_at generated by the DB
    return user


@router.post("/login")
def login(
    form: OAuth2PasswordRequestForm = Depends(),
    db: Session = Depends(get_db),
) -> dict:
    user = db.scalar(select(User).where(User.email == form.username))
    # Same error for "no such user" and "wrong password": distinguishing
    # them would let attackers enumerate registered emails.
    if user is None or not verify_password(form.password, user.hashed_password):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Incorrect email or password",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return {"access_token": create_access_token(str(user.id)), "token_type": "bearer"}
